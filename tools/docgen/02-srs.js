const {
    AlignmentType, BorderStyle, Paragraph, ShadingType, Table, TableCell, TableRow, TextRun, VerticalAlign, WidthType,
} = require('docx');
const {
    INFO, CONTENT_WIDTH, h1, h2, h3, p, bullets, figure, runs, buildDocument, save,
} = require('./lib');

/**
 * 数据表（与 lib.table 外观相同）。与 lib.table 的区别：
 * 1. 不超过 15 行的表格整体保持在同一页（各段落设置 keepNext），避免表头孤立在页尾；
 * 2. 较长的表格允许跨页，此时不设置 cantSplit —— LibreOffice / WPS 在“跨页重复表头 + 行禁止跨页”
 *    同时启用时，表格跨页后的行不显示（Word 正常）。
 */
const BORDER = { style: BorderStyle.SINGLE, size: 4, color: '9CA3AF' };
const BORDERS = { top: BORDER, bottom: BORDER, left: BORDER, right: BORDER };
const CAPTION_FONT = { ascii: 'Arial', hAnsi: 'Arial', eastAsia: '黑体' };

function columnWidthsOf(ratios) {
    const sum = ratios.reduce((a, b) => a + b, 0);
    const widths = ratios.map((r) => Math.floor((r / sum) * CONTENT_WIDTH));
    widths[widths.length - 1] += CONTENT_WIDTH - widths.reduce((a, b) => a + b, 0);
    return widths;
}

function tableCaption(title) {
    return new Paragraph({
        alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 200, after: 80 },
        children: [new TextRun({ text: title, font: CAPTION_FONT, size: 21 })],
    });
}

function makeCell(value, width, { fill, bold = false, align = AlignmentType.LEFT, keepNext = false, header = false }) {
    const lines = Array.isArray(value) ? value : String(value ?? '').split('\n');
    return new TableCell({
        width: { size: width, type: WidthType.DXA },
        shading: fill ? { type: ShadingType.CLEAR, fill, color: 'auto' } : undefined,
        verticalAlign: VerticalAlign.CENTER,
        margins: { top: header ? 60 : 50, bottom: header ? 60 : 50, left: 100, right: 100 },
        borders: BORDERS,
        children: lines.map((line) => new Paragraph({
            alignment: align, keepNext, spacing: { line: 300 }, children: runs(line, { size: 21, bold }),
        })),
    });
}

function table({ headers, rows, widths, caption: title, center = [], keepTogether = rows.length <= 15 }) {
    const columnWidths = columnWidthsOf(widths || headers.map(() => 1));
    const headerRow = new TableRow({
        tableHeader: true,
        cantSplit: keepTogether,
        children: headers.map((h, i) => makeCell(h, columnWidths[i], {
            fill: 'FDE7D3', bold: true, align: AlignmentType.CENTER, keepNext: keepTogether, header: true,
        })),
    });
    const bodyRows = rows.map((row, r) => new TableRow({
        cantSplit: keepTogether,
        children: row.map((v, i) => makeCell(v, columnWidths[i], {
            align: center.includes(i) ? AlignmentType.CENTER : AlignmentType.LEFT,
            keepNext: keepTogether && r < rows.length - 1,
        })),
    }));
    return [
        title && tableCaption(title),
        new Table({ width: { size: CONTENT_WIDTH, type: WidthType.DXA }, columnWidths, rows: [headerRow, ...bodyRows] }),
        new Paragraph({ spacing: { after: 120 }, children: [] }),
    ].filter(Boolean);
}

/** 键值表（与 lib.kvTable 外观相同），整张表保持在同一页 */
function kvTable(pairs, { caption: title, keyWidth = 1, valueWidth = 4 } = {}) {
    const [kw, vw] = columnWidthsOf([keyWidth, valueWidth]);
    const rows = pairs.map(([k, v], r) => {
        const keepNext = r < pairs.length - 1;
        return new TableRow({
            cantSplit: true,
            children: [
                makeCell(k, kw, { fill: 'F3F4F6', bold: true, align: AlignmentType.CENTER, keepNext }),
                makeCell(v, vw, { keepNext }),
            ],
        });
    });
    return [
        title && tableCaption(title),
        new Table({ width: { size: CONTENT_WIDTH, type: WidthType.DXA }, columnWidths: [kw, vw], rows }),
        new Paragraph({ spacing: { after: 120 }, children: [] }),
    ].filter(Boolean);
}

/** 与 lib.p 相同的正文段落，但与下一段保持在同一页（用于引出代码块的段落） */
function pKeep(text) {
    return new Paragraph({
        alignment: AlignmentType.JUSTIFIED, indent: { firstLine: 480 }, keepNext: true,
        spacing: { line: 360, before: 0, after: 0 }, children: runs(text),
    });
}

/** 代码片段（与 lib.code 外观相同），整段保持在同一页 */
function code(lines) {
    return lines.map((line, i) => new Paragraph({
        shading: { type: ShadingType.CLEAR, fill: 'F5F5F5', color: 'auto' },
        keepNext: i < lines.length - 1,
        spacing: { line: 260, before: i === 0 ? 120 : 0, after: i === lines.length - 1 ? 120 : 0 },
        indent: { left: 240, right: 240 },
        children: [new TextRun({ text: line.length ? line : ' ', font: { ascii: 'Consolas', hAnsi: 'Consolas', eastAsia: '宋体' }, size: 18 })],
    }));
}

